import { expect, test } from "@playwright/test";
import fs from "node:fs";
import { createTempleRoutingServer } from "../helpers/temple-routing-server.mjs";
import { testAccessToken } from "../helpers/supabase-auth-fixture.mjs";
import { ADMIN_ACCESS_COOKIE } from "../../api/admin/_auth.js";
import { createLegacyTempleSlug } from "../../src/data/temple-slugs.js";
import { templeDatasets } from "../../src/lib/temple-routing.js";

test.describe.configure({ mode: "serial" });
let fixture;
test.beforeAll(async () => { fixture = await createTempleRoutingServer(); });
test.afterAll(async () => { await fixture?.close(); });
const legacy = createLegacyTempleSlug(templeDatasets.popular[0]);
const key = `popular:${legacy}`;
const output = "artifacts/temple-slugs";

test("Admin custom URL publishes through the real API to SSR, aliases, sitemap and public links", async ({ page, request, context }) => {
  test.setTimeout(180_000);
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await context.addCookies([{ name: ADMIN_ACCESS_COOKIE, value: testAccessToken(), url: fixture.url }]);
  await page.addInitScript(() => { localStorage.setItem("mongkolwela.admin.sidebarCollapsed", "1"); localStorage.setItem("mongkolwela.pdpa.analytics", "declined"); });
  const old = await request.get(`${fixture.url}/temples/popular/${encodeURIComponent(legacy)}/?source=old`, { maxRedirects: 0 });
  expect(old.status()).toBe(308);
  expect(old.headers().location).toBe("/temples/popular/wat-rakhang-khositaram/?source=old");
  await page.goto(`${fixture.url}/admin/`, { waitUntil: "domcontentloaded" });
  await expect(page.locator("#adminStatus")).toHaveText("พร้อมใช้งาน");
  await page.locator('#adminNav [data-section="temples"]').click();
  await page.locator("[data-edit-temple]").first().click();
  const slug = page.getByRole("textbox", { name: "ชื่อ URL", exact: true });
  await expect(slug).toHaveValue("wat-rakhang-khositaram");
  await page.getByRole("radio", { name: "กำหนดเอง", exact: true }).check();
  await slug.fill("wat-arun");
  await page.getByRole("button", { name: "บันทึก", exact: true }).click();
  await expect(page.locator("[data-temple-slug-error]")).toContainText("ถูกใช้แล้ว");
  await expect(slug).toBeFocused();
  await slug.fill("bad slug");
  await expect(slug).toHaveAttribute("aria-invalid", "true");
  await slug.fill("temple-of-bells");
  await page.getByLabel("ชื่อสถานที่", { exact: true }).fill("วัดระฆังโฆสิตาราม ทดสอบ");
  await expect(slug).toHaveValue("temple-of-bells");
  fs.mkdirSync(output, { recursive: true });
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: `${output}/admin-custom-desktop.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  await slug.scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${output}/admin-custom-mobile.png` });
  expect(await page.locator(".mw-admin-drawer-body").evaluate(node => node.scrollWidth <= node.clientWidth + 1)).toBe(true);
  await page.getByRole("button", { name: "บันทึก", exact: true }).click();
  const publication = page.waitForResponse(response => response.url().endsWith("/api/admin/content") && response.request().method() === "POST");
  await page.locator('[data-action="publish"]').first().click();
  const response = await publication;
  expect(response.status(), await response.text()).toBe(200);
  expect(fixture.state.content.temples.records[key].slug).toBe("temple-of-bells");
  expect(fixture.state.writes).toBe(1);
  for (const alias of [legacy, "wat-rakhang-khositaram"]) {
    const redirected = await request.get(`${fixture.url}/temples/popular/${encodeURIComponent(alias)}/`, { maxRedirects: 0 });
    expect(redirected.status()).toBe(308);
    expect(redirected.headers().location).toBe("/temples/popular/temple-of-bells/");
  }
  const detail = await request.get(`${fixture.url}/temples/popular/temple-of-bells/`);
  expect(detail.status()).toBe(200);
  const html = await detail.text();
  expect(html).toContain('href="https://mongkolwela.vercel.app/temples/popular/temple-of-bells/"');
  expect(html).toContain("วัดระฆังโฆสิตาราม ทดสอบ");
  const sitemap = await (await request.get(`${fixture.url}/sitemap.xml`)).text();
  expect(sitemap).toContain("/temples/popular/temple-of-bells/</loc>");
  expect(sitemap).not.toContain("/temples/popular/wat-rakhang-khositaram/</loc>");
  await page.goto(`${fixture.url}/temples/popular/`);
  await expect(page.locator("html")).toHaveAttribute("data-cms-ready", "true");
  await expect(page.locator('[data-popular-temple-detail][href="/temples/popular/temple-of-bells/"]')).toBeVisible();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${fixture.url}/admin/`, { waitUntil: "domcontentloaded" });
  await expect(page.locator("#adminStatus")).toHaveText("พร้อมใช้งาน");
  await page.locator('#adminNav [data-section="temples"]').click();
  await page.locator("[data-edit-temple]").first().click();
  await expect(slug).toHaveValue("temple-of-bells");
  await expect(page.getByRole("radio", { name: "กำหนดเอง", exact: true })).toBeChecked();
  await slug.fill("cancel-this-url");
  await page.getByRole("button", { name: "ยกเลิก", exact: true }).click();
  await page.locator("[data-edit-temple]").first().click();
  await expect(slug).toHaveValue("temple-of-bells");
  await expect(page.getByRole("radio", { name: "กำหนดเอง", exact: true })).toBeChecked();
  expect(errors).toEqual([]);
});

test("new auto-generated place publishes without a rebuild, outage never serves stale details", async ({ page, request, context }) => {
  test.setTimeout(180_000);
  let releaseGenerator: () => void;
  const generatorReady = new Promise<void>(resolve => { releaseGenerator = resolve; });
  await page.route("**/_astro/temple-slugs.*.js", async route => {
    await generatorReady;
    await route.continue();
  });
  await context.addCookies([{ name: ADMIN_ACCESS_COOKIE, value: testAccessToken(), url: fixture.url }]);
  await page.goto(`${fixture.url}/admin/`, { waitUntil: "domcontentloaded" });
  await expect(page.locator("#adminStatus")).toHaveText("พร้อมใช้งาน");
  await page.locator('#adminNav [data-section="temples"]').click();
  await page.getByRole("button", { name: "เพิ่มวัด", exact: true }).click();
  await page.getByLabel("ชื่อสถานที่", { exact: true }).fill("วัดทดสอบใหม่");
  // Area changes replace the drawer while the optional transliterator is loading.
  await page.locator('select[data-temple-field="province"]').selectOption("กรุงเทพมหานคร", { force: true });
  releaseGenerator();
  await expect(page.getByRole("textbox", { name: "ชื่อ URL", exact: true })).toHaveValue("wat-thot-sop-mai");
  await page.getByRole("button", { name: "บันทึก", exact: true }).click();
  const publication = page.waitForResponse(response => response.url().endsWith("/api/admin/content") && response.request().method() === "POST");
  await page.locator('[data-action="publish"]').first().click();
  expect((await publication).status()).toBe(200);
  const created = await request.get(`${fixture.url}/temples/popular/wat-thot-sop-mai/`);
  expect(created.status()).toBe(200);
  expect(await created.text()).toContain("วัดทดสอบใหม่");
  const missing = await request.get(`${fixture.url}/temples/popular/no-such-place/`);
  expect(missing.status()).toBe(404);
  fixture.state.outage = true;
  const outage = await request.get(`${fixture.url}/temples/popular/wat-arun/`);
  expect(outage.status()).toBe(503);
  expect(outage.headers()["cache-control"]).toBe("no-store");
  fixture.state.outage = false;
  expect((await request.get(`${fixture.url}/temples/popular/wat-arun/`)).status()).toBe(200);
});
