import { expect, test } from "@playwright/test";
import fs from "node:fs/promises";
import path from "node:path";
import { createAdminAuthPreview } from "../helpers/admin-auth-preview.mjs";
import { TEST_ADMIN_EMAIL, TEST_ADMIN_PASSWORD } from "../helpers/supabase-auth-fixture.mjs";

let preview;
test.beforeAll(async () => { preview = await createAdminAuthPreview({ astroBase: process.env.PLAYWRIGHT_BASE_URL || "http://127.0.0.1:4324" }); });
test.afterAll(async () => { await preview?.close(); });

test("email login, errors, current identity, reload and logout use real API handlers", async ({ page, context }, info) => {
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`${preview.base}/admin/`);
  const email = page.getByLabel("อีเมล", { exact: true });
  const password = page.getByLabel("รหัสผ่าน", { exact: true });
  const submit = page.getByRole("button", { name: "เข้าสู่ระบบ", exact: true });
  await expect(email).toBeVisible();
  await expect(page.locator(".mw-admin-login")).toHaveCSS("display", "grid");
  await expect(page.getByLabel("ชื่อผู้แก้ไข")).toHaveCount(0);
  await email.fill(TEST_ADMIN_EMAIL);
  await password.fill("wrong");
  await submit.click();
  await expect(page.getByRole("alert")).toContainText("อีเมลหรือรหัสผ่านไม่ถูกต้อง");
  await expect(email).toHaveValue(TEST_ADMIN_EMAIL);
  await expect(submit).toBeEnabled();
  await email.fill("member@example.test");
  await password.fill(TEST_ADMIN_PASSWORD);
  await submit.click();
  await expect(page.getByRole("alert")).toContainText("ไม่มีสิทธิ์");
  const dir = path.join(process.cwd(), ".local/admin-auth-qa");
  await fs.mkdir(dir, { recursive: true });
  await page.screenshot({ path: path.join(dir, `login-denied-${info.project.name}.png`), fullPage: true });
  await email.fill(TEST_ADMIN_EMAIL);
  await submit.click();
  await expect(page.locator(".mw-admin-profile strong")).toHaveText(TEST_ADMIN_EMAIL);
  await expect(page.locator("#adminContent")).toBeVisible();
  const authCookies = (await context.cookies()).filter(cookie => cookie.name.startsWith("mw_admin_") && cookie.value);
  expect(authCookies).toHaveLength(2);
  expect(authCookies.every(cookie => cookie.httpOnly && cookie.sameSite === "Strict")).toBe(true);
  expect(await page.evaluate(() => document.cookie)).not.toContain("mw_admin_");
  expect(await page.evaluate(() => JSON.stringify(localStorage))).not.toContain("access_token");
  await page.reload();
  await expect(page.locator(".mw-admin-profile strong")).toHaveText(TEST_ADMIN_EMAIL);
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(2);
  await page.locator('[data-section="navigation"]').click();
  await page.locator('[data-action="add-nav-tab"]').click();
  await page.getByRole("button", { name: "ออกจากระบบ", exact: true }).first().click();
  const confirmation = page.getByRole("dialog", { name: "ออกจากระบบโดยยังไม่บันทึก?" });
  await expect(confirmation).toBeVisible();
  await confirmation.getByRole("button", { name: "ยกเลิก", exact: true }).click();
  await expect(page.locator(".mw-admin-profile strong")).toHaveText(TEST_ADMIN_EMAIL);
  await page.getByRole("button", { name: "ออกจากระบบ", exact: true }).first().click();
  await confirmation.getByRole("button", { name: "ออกจากระบบ", exact: true }).click();
  await expect(email).toBeVisible();
  await page.reload();
  await expect(email).toBeVisible();
  expect((await context.cookies()).filter(cookie => cookie.name.startsWith("mw_admin_") && cookie.value)).toHaveLength(0);
  await page.screenshot({ path: path.join(dir, `login-${info.project.name}.png`), fullPage: true });
  expect(errors).toEqual([]);
});
