test("catalog source failure is retryable; donation edit clears public approval", async ({ page }) => {
  let fail = true;
  await page.route("**/api/commerce", async route => { if (fail && route.request().method() === "GET") { fail = false; return route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ ok: false, error: "แหล่งข้อมูลไม่พร้อม" }) }); } return route.continue(); });
  await page.goto(`${base}/shop/`);
  await expect(page.getByText("แหล่งข้อมูลไม่พร้อม", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "ลองใหม่", exact: true }).click();
  await expect(page.getByRole("heading", { name: fixture.product.title })).toBeVisible();
  await sellerLogin(page);
  await page.getByRole("button", { name: "ช่องทาง e-Donation", exact: true }).click();
  await page.getByRole("button", { name: "แก้ไข", exact: true }).click();
  await page.getByLabel("ชื่อหน่วยรับบริจาค", { exact: true }).fill("เปลี่ยนข้อมูล ต้องรอตรวจใหม่");
  await page.getByRole("button", { name: "บันทึกรายการ", exact: true }).click();
  await expect(page.getByText("บันทึกแล้ว", { exact: true })).toBeVisible();
  expect((await (await page.request.get(`${base}/api/commerce`)).json()).channels).toHaveLength(0);
  await page.route("**/api/commerce?templeId=*", route => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ ok: false, code: "COMMERCE_DISABLED", error: "ระบบร้านค้าและร่วมบุญยังไม่เปิดบริการ" }) }));
  const temple = (await loadTempleCatalog()).find(t => t.key === fixture.product.templeId);
  await page.goto(`${base}/temples/${temple.collection}/${temple.slug}/`);
  await expect(page.locator("[data-temple-commerce]")).toBeHidden();
  await expect(page.locator("[data-temple-commerce]")).toHaveCount(1);
});

