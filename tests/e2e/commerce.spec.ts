async function sellerLogin(page) {
  await page.goto(`${base}/seller/`);
  await page.getByLabel("อีเมล", { exact: true }).fill("seller@example.test");
  await page.getByLabel("รหัสผ่าน", { exact: true }).fill("preview-only-password");
  await page.getByRole("button", { name: "เข้าสู่ระบบ", exact: true }).click();
  await expect(page.getByRole("heading", { name: "สินค้า", exact: true })).toBeVisible();
}
async function noOverflow(page) { expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true); }
async function readyFullPage(page) {
  await page.evaluate(() => document.fonts.ready);
  await page.locator(".site-footer").scrollIntoViewIfNeeded();
  await expect.poll(() => page.locator(".site-footer img").evaluateAll(images => images.every((img: HTMLImageElement) => img.complete && img.naturalWidth > 0))).toBe(true);
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: "instant" }));
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(0);
}

